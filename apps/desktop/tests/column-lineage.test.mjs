import assert from 'node:assert/strict';
import { columnPaths, columnHops, fieldKey, nextFieldIndex } from '../src/features/lineage/column-model.ts';
const field = (dataset_id, column = 'id') => ({ dataset_id, column });
const edge = (from, to) => ({ from: field(from), to: field(to), kind: 'passthrough', expression: 'id', via: {} });
const graph = { root: field('b'), nodes: ['a','b','c','sibling'].map(id => field(id)), edges: [edge('b','c'),edge('a','b'),edge('a','sibling')], usage: [], incomplete: false };
const path = columnPaths(graph, field('b'));
assert.deepEqual([...path.nodes].sort(), ['a','b','c'].map(id => fieldKey(field(id))).sort());
assert.deepEqual([...path.edges].sort(), [0,1]);
assert.deepEqual([...columnPaths(graph,field('b'),'upstream').edges],[1]);
assert.deepEqual([...columnPaths(graph,field('b'),'downstream').edges],[0]);
assert.equal(columnPaths(graph,field('b'),'both',0).nodes.size,1);
assert.equal(columnPaths({...graph,edges:[edge('a','b'),edge('b','a')]},field('a')).edges.size,2);
assert.deepEqual(columnHops({...graph,edges:[edge('b','c'),edge('a','b')]}),[1,0]);
assert.deepEqual(columnHops({...graph,edges:[edge('a','b'),edge('b','a')]}),[0,1]);
assert.deepEqual(columnHops({...graph,edges:[edge('b','c'),edge('a','b'),edge('x','b')]}),[1,2,0]);
assert.notEqual(fieldKey(field('a:b','c')),fieldKey(field('a','b:c')));
assert.equal(nextFieldIndex(0,3,'ArrowUp'),2);
assert.equal(nextFieldIndex(2,3,'ArrowRight'),0);
assert.equal(nextFieldIndex(1,3,'Home'),0);
assert.equal(nextFieldIndex(1,3,'End'),2);
assert.equal(nextFieldIndex(0,0,'ArrowDown'),-1);
console.log('Column lineage paths, branches, cycles, ordering and keyboard navigation passed');
