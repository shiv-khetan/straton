assert.equal(useLibrary.getState().favorites.length,1);
assert.equal(useLibrary.getState().favorites[0].scope,'other|u');
for(let i=0;i<120;i++)useLibrary.getState().visit({...entry,id:'dataset:'+i,entityId:String(i)});
assert.equal(useLibrary.getState().recent.length,100);
console.log('Device-local library validates persisted entries, scopes favorites by engine/account, deduplicates recents and caps storage.');
