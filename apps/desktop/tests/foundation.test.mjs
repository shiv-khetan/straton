assert.equal(useLibrary.getState().recent.length,1);
assert.equal(useLibrary.getState().recent[0].visitedAt,2);
useLibrary.getState().visit({...entry,scope:'other|u'});
assert.equal(useLibrary.getState().recent.length,2);
useLibrary.getState().toggle(entry);
useLibrary.getState().toggle({...entry,scope:'other|u'});
