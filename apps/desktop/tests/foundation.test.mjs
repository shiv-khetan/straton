import assert from 'node:assert/strict';
import { navigateHistory, stepHistory, isRoute } from '../src/stores/route-history.ts';
import { useRouteStore } from '../src/stores/route.ts';
import { clampSidebarWidth, parseSidebar, navKeyboardIndex, defaultSidebar } from '../src/stores/sidebar-state.ts';
import { notificationList, eventQueryKeys } from '../src/lib/events.ts';
import { queryKeys } from '../src/lib/queryKeys.ts';
import { safeStorage } from '../src/stores/storage.ts';

const start = { entries: ['Connect'], index: 0 };
const first = navigateHistory(start, 'Dashboard');
const second = navigateHistory(first, 'SQL');
assert.deepEqual(start, { entries: ['Connect'], index: 0 });
assert.equal(navigateHistory(second, 'SQL'), second);
const back = stepHistory(second, -1);
assert.equal(back.entries[back.index], 'Dashboard');
assert.equal(stepHistory(back, 1).entries[2], 'SQL');
assert.deepEqual(navigateHistory(back, 'Jobs'), { entries: ['Connect', 'Dashboard', 'Jobs'], index: 2 });
assert.equal(stepHistory(start, -10).index, 0);
assert.equal(stepHistory(second, 100).index, 2);
assert.equal(stepHistory(second, NaN).index, 2);
assert.equal(isRoute('SQL'), true);
assert.equal(isRoute('fake'), false);
let long = start;
for (let i = 0; i < 150; i++) long = navigateHistory(long, i % 2 ? 'SQL' : 'Jobs');
assert.equal(long.entries.length, 100);
assert.equal(long.index, 99);
useRouteStore.getState().reset('Dashboard');
useRouteStore.getState().navigate('SQL');
useRouteStore.getState().navigate('Jobs');
useRouteStore.getState().back();
assert.equal(useRouteStore.getState().page, 'SQL');
useRouteStore.getState().forward();
assert.equal(useRouteStore.getState().page, 'Jobs');
useRouteStore.getState().back();
useRouteStore.getState().navigate('Models');
useRouteStore.getState().forward();
assert.equal(useRouteStore.getState().page, 'Models');
assert.deepEqual(useRouteStore.getState().entries, ['Dashboard', 'SQL', 'Models']);

for (const [value, expected] of [[0,208],[9999,336],[248.6,249],[NaN,248],[Infinity,248],[-Infinity,248]]) assert.equal(clampSidebarWidth(value), expected);
for (const value of [null, 'broken {', '[]', 'null', 42, undefined]) assert.deepEqual(parseSidebar(value), defaultSidebar);
assert.deepEqual(parseSidebar('{"width":300,"collapsed":true,"expandedGroups":{"Data":false}}'), { ...defaultSidebar, width:300, collapsed:true, expandedGroups:{ ...defaultSidebar.expandedGroups, Data:false } });
assert.deepEqual(parseSidebar({width:'300', collapsed:'yes', expandedGroups:{Data:'false', Workspace:false, fake:false}}), { ...defaultSidebar, expandedGroups:{ ...defaultSidebar.expandedGroups, Workspace:false } });
const parsed = parseSidebar(null); parsed.expandedGroups.Workspace = false;
assert.equal(defaultSidebar.expandedGroups.Workspace, true);
for (const [index,key,length,want] of [[0,'ArrowUp',4,3],[3,'ArrowDown',4,0],[2,'Home',4,0],[1,'End',4,3],[2,'Enter',4,2],[-1,'ArrowDown',4,1],[9,'ArrowUp',4,2],[0,'ArrowDown',0,-1]]) assert.equal(navKeyboardIndex(index,key,length),want);

const events = [{type:'run.state',id:'r',state:'failed',received_at:1234},{type:'resync_required',received_at:1233},{type:'catalog.changed',message:'Catalog discovered',received_at:1200},{type:'engine.hello'}];
const notices = notificationList(events);
assert.equal(notices.length,3);
assert.deepEqual(notices.map(n => [n.title,n.entity,n.level]), [['run.state → failed','r','ERROR'],['Catalog discovered','Engine','INFO'],['engine.hello','Engine','INFO']]);
assert.equal(notices[0].receivedAt,1234);
assert.equal(notices[2].receivedAt,undefined);
assert.equal(new Set(notificationList([events[0],events[0]]).map(n=>n.key)).size,2);
assert.deepEqual(notificationList([],30),[]);
assert.deepEqual(notificationList(events,-1),[]);
assert.equal(notificationList(events,1).length,1);
assert.deepEqual(eventQueryKeys({type:'resync_required'}),[queryKeys.all]);
assert.ok(eventQueryKeys({type:'run.state'}).includes(queryKeys.runs));
assert.ok(eventQueryKeys({type:'run.state'}).includes(queryKeys.catalog));
assert.ok(eventQueryKeys({type:'catalog.changed'}).includes(queryKeys.datamap));
assert.ok(eventQueryKeys({type:'model.changed'}).includes(queryKeys.models));
assert.deepEqual(eventQueryKeys({type:'unrelated'}),[]);
const previous = Object.getOwnPropertyDescriptor(globalThis,'localStorage');
Object.defineProperty(globalThis,'localStorage',{configurable:true,get(){throw new Error('Storage unavailable');}});
assert.equal(safeStorage.getItem('sidebar'),null);
assert.doesNotThrow(()=>safeStorage.setItem('sidebar','value'));
assert.doesNotThrow(()=>safeStorage.removeItem('sidebar'));
if(previous)Object.defineProperty(globalThis,'localStorage',previous);else delete globalThis.localStorage;
console.log('Foundation history/store, sidebar clamping/parsing/storage, nav keyboard math and real notification mapping passed.');

const { parseEntries, useLibrary } = await import('../src/stores/library.ts');
assert.deepEqual(parseEntries(null),[]);
assert.deepEqual(parseEntries([{},null,{id:'x',label:'x',kind:'unknown',route:'Dashboard',scope:'s',visitedAt:1}]),[]);
const entry = {id:'dataset:d', label:'orders', kind:'dataset', route:'Data Map', entityId:'d', scope:'engine|u', visitedAt:1};
assert.deepEqual(parseEntries([entry]),[entry]);
assert.deepEqual(parseEntries([{...entry,entityId:undefined}]),[]);
assert.deepEqual(parseEntries([{...entry,route:'SQL'}]),[]);
